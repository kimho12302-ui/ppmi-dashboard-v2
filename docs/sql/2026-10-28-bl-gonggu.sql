select to_char(date, 'YYYY-MM') as month,
       sum(revenue) filter (where coalesce(lineup, '') <> '' or channel like '공구%') as gonggu,
       sum(revenue) filter (where coalesce(lineup, '') = '' and channel not like '공구%') as self
from product_sales where brand = 'balancelab' and date between '2025-12-01' and '2026-05-31'
group by 1 order by 1;

