--   2025-12  공구 0 → 5,600,000  /  자체 5,600,000 → 0
--   2026-01  공구 0 → 32,125,500  /  자체 34,389,501 → 2,264,001
--   2026-02  공구 0 → 3,686,000  /  자체 6,327,000 → 2,641,000
