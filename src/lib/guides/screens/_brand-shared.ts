import type { Block, ManualSection, ScreenGuide, TourStep } from "../types";

// ── 블록 짧게 쓰기 (예산·매체별 집행 파일도 같이 쓴다) ──
export const p = (text: string): Block => ({ kind: "p", text });
export const h = (text: string): Block => ({ kind: "h", text });
export const list = (...items: string[]): Block => ({ kind: "list", items });
export const steps = (...items: string[]): Block => ({ kind: "steps", items });
export const table = (head: string[], rows: string[][]): Block => ({ kind: "table", head, rows });
export const info = (text: string): Block => ({ kind: "note", tone: "info", text });
export const warn = (text: string): Block => ({ kind: "note", tone: "warn", text });
export const qa = (q: string, a: string): Block => ({ kind: "qa", q, a });

/** 브랜드마다 다른 것 */
export interface BrandSpec {
  key: string;
  /** 주소 끝 (/brand/○○) */
  slug: string;
  /** 사이드바 메뉴 이름 */
  menu: string;
  /** 화면 맨 위에 찍히는 제목 (BRAND_LABELS) */
  screenTitle: string;
  summary: string;
  /** 개요 첫머리 문단 */
  intro: string[];
  /** 밸런스랩처럼 공구(공동구매)를 따로 세는 브랜드 */
  gonggu: boolean;
  /** 「라인업별」·「라인업별 매출」을 묶는 규칙 설명 */
  lineupRule: Block[];
  /** 판매처 절 끝에 붙는 이 브랜드 판매처 사정 */
  storeNotes: Block[];
  /** 광고 매체 절 끝에 붙는 이 브랜드 매체 사정 (운영 안 하는 매체, 0원이 정상인 매체) */
  adNotes: Block[];
  /** 「○○만의 사정」 절. 비우면 절을 만들지 않는다 */
  ownSection?: ManualSection;
  /** 브랜드 고유 자주 묻는 질문 (공통 질문 앞에 둔다) */
  faq: Block[];
}

