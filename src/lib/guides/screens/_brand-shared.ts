export function buildBrandGuide(s: BrandSpec): ScreenGuide {
  const manual: ManualSection[] = [
    overview(s),
    layout(s),
    period(),
    kpi(s),
    mix(s),
    stores(s),
    ads(s),
    products(s),
    rules(s),
    colors(s),
  ];
  if (s.ownSection) manual.push(s.ownSection);
  manual.push(howto(s), sources(s), {
    id: "faq",
    title: "자주 묻는 질문",
    blocks: [...s.faq, ...commonFaq(s)],
  });
  return { key: s.key, title: s.menu, summary: s.summary, tour: tour(s), manual };
}
