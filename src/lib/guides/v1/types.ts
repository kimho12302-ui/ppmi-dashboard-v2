// 화면별 이용 가이드의 틀 (2026-11-06).
//
// 김호: "각 화면마다 오른쪽 상단쯤에 이용 가이드 및 사용 메뉴얼 만들어줘".
// 모든 가이드는 같은 다섯 칸을 채운다. 칸 이름을 타입으로 고정해 두면 화면마다 틀이 어긋날 수 없다.
//
// 쓰는 규칙
//  - 독자는 대시보드를 처음 쓰는 마케팅 팀원이다. 개발 용어를 쓰지 않는다.
//  - 버튼·카드 이름은 화면에 찍힌 글자 그대로 「」 로 감싼다. 없는 버튼을 적지 않는다.
//  - 긴 대시(U+2014)와 하이픈 두 개를 쓰지 않는다.
//  - 화면 코드를 바꿔 버튼 이름이 달라지면 여기 문구도 같이 고친다.

export interface GuideItem {
  /** 카드·차트·표 이름 또는 할 일의 제목 */
  name: string;
  /** 무엇을 보여 주는지, 어떻게 하는지 (한두 문장) */
  desc: string;
}

export interface Guide {
  /** 드로어 머리에 찍히는 화면 이름 */
  title: string;
  /** 이 화면은 무엇을 보나 (2~3줄) */
  what: string[];
  /** 화면 구성: 위에서부터 순서대로 */
  layout: GuideItem[];
  /** 이렇게 쓰세요: 자주 하는 일 2~4개 */
  howTo: GuideItem[];
  /** 숫자 읽을 때 주의: 이 화면 고유 함정 */
  caveats: string[];
  /** 데이터 출처·갱신 */
  sources: string[];
}
